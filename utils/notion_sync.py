"""
Direct Notion Sync Tool for StorytimeTik Studio.
Connects with the 'Payhib Store Content Hub' Notion database to push ready-to-post scripts,
captions, hashtags, and schedule status.
"""

from typing import Dict, Any, Optional

PAYHIB_CONTENT_HUB_DB_ID = "6b1fc299-0879-4e5e-8d48-d45af93fd221"
PAYHIB_DATA_SOURCE_ID = "3445be20-1c82-4109-a7dc-62a1d5f8ca5a"

def format_notion_payload(story: Dict[str, Any], scheduled_date: Optional[str] = None) -> Dict[str, Any]:
    """
    Constructs the schema-compliant properties payload for the Payhib Content Hub database.
    """
    caption_text = f"{story.get('hook', '')}\n\nFull Voiceover Script:\n{story.get('full_voiceover', '')}\n\n{' '.join(story.get('hashtags', []))}"
    # Rich text objects must not exceed 2000 chars
    caption_truncated = caption_text[:1900]

    properties = {
        "Content Title": {
            "title": [
                {"type": "text", "text": {"content": story.get("title", "Untitled Storytime Video")[:100]}}
            ]
        },
        "Status": {
            "select": {"name": "Ready to Post"}
        },
        "Platform": {
            "multi_select": [{"name": "TikTok"}, {"name": "Instagram"}]
        },
        "Content Type": {
            "multi_select": [{"name": "Promotion"}, {"name": "User Generated"}]
        },
        "Caption": {
            "rich_text": [
                {"type": "text", "text": {"content": caption_truncated}}
            ]
        },
        "Notes": {
            "rich_text": [
                {"type": "text", "text": {"content": f"Est. Duration: {story.get('estimated_duration_sec', 60)}s | Words: {story.get('word_count', 120)} | Generated by StorytimeTik"}}
            ]
        }
    }

    if scheduled_date:
        properties["Scheduled Post Date"] = {"date": {"start": scheduled_date}}

    return {
        "parent": {"data_source_id": PAYHIB_DATA_SOURCE_ID},
        "properties": properties
    }
